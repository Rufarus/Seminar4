# tests/conftest.py
import pytest


@pytest.fixture(scope="session")
def valid_ips() -> list[str]:
    """Набор синтаксически корректных ip-адресов."""
    return [
        "0.0.0.0",
        "192.0.0.1",
        "255.255.255.255",
    ]


@pytest.fixture(scope="session")
def invalid_ips() -> list[str]:
    """Набор заведомо некорректных ip-адресов."""
    return [
        "",                       # пустая строка
        "0000",                   # нет точек
        ".0.0.0",                 # нет числа
        "256.0.0.0",              # число больше 255
        "0.0 .0.0",               # пробел
        "0..0.0.0",               # двойная точка
        "0.0.0.0\n",              # перевод строки в конце (важно: $ не матчит \n)
        "O.0.0.0",                # буква вместо цифры
    ]
